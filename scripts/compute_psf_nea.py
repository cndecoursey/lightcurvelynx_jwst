"""Compute NIRCam PSF noise-equivalent areas (NEA) with STPSF and store them in the config.

    python scripts/compute_psf_nea.py                         # the six JETS filters
    python scripts/compute_psf_nea.py --filters F090W F410M   # other filters (merged into the file)

Writes config/nircam_psf_nea.yaml, which jwst_survey.py uses for ``psf_footprint`` (the
number of native pixels whose background, read and dark noise enter a point-source flux
measurement). Requires STPSF and its data files (STPSF_PATH); run it where those are
installed, then commit the YAML file.

Method
------
For each filter, STPSF computes the PSF on the native detector grid including optical
distortion, charge diffusion and inter-pixel capacitance (the ``DET_DIST`` extension).
The NIRCam PSF is undersampled, so the NEA depends on where the source falls within a
pixel; it is averaged over four sub-pixel source positions (offsets of 0 and 1/2 pixel in
each axis). The PSF is normalized to the total source flux (STPSF ``normalize="first"``)
and is not renormalized within the computed image, so light outside the image correctly
increases the NEA:

    NEA = 1 / sum(p_i^2)          (optimal PSF-fitting photometry)

This is the noise area of PSF photometry on native pixels. Aperture photometry and
resampling to a mosaic both increase the effective area; those are calibrated separately.
"""

import argparse
import sys
from datetime import date
from pathlib import Path

import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from utils import NIRCAM_PSF_NEA_FILE, noise_equivalent_area  # noqa: E402

JETS_FILTERS = ["F115W", "F150W", "F200W", "F277W", "F356W", "F444W"]
PHASES = [(0.0, 0.0), (0.5, 0.0), (0.0, 0.5), (0.5, 0.5)]  # sub-pixel offsets, native pixels


def is_short_wavelength(filt):
    """True for SW-channel filters (F070W-F212N); LW filters start at F250M."""
    return int(filt[1:4]) < 250


def nea_for_filter(stpsf, filt, *, detector, fov_pixels, oversample):
    """Phase-averaged NEA and supporting numbers for one filter."""
    nc = stpsf.NIRCam()
    nc.filter = filt          # selects the channel
    nc.detector = detector    # then the specific detector
    pixscale = float(nc.pixelscale)

    neas, enclosed = [], []
    for dx, dy in PHASES:
        nc.options["source_offset_x"] = dx * pixscale  # arcsec
        nc.options["source_offset_y"] = dy * pixscale
        psf = nc.calc_psf(fov_pixels=fov_pixels, oversample=oversample)
        p = psf["DET_DIST"].data
        neas.append(noise_equivalent_area(p))
        enclosed.append(float(np.sum(p)))
    return {
        "nea_pix": round(float(np.mean(neas)), 3),
        "nea_min_pix": round(float(np.min(neas)), 3),
        "nea_max_pix": round(float(np.max(neas)), 3),
        "enclosed_fraction": round(float(np.mean(enclosed)), 4),
        "detector": detector,
        "pixel_scale_arcsec": round(pixscale, 5),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--filters", nargs="+", default=JETS_FILTERS)
    parser.add_argument("--sw-detector", default="NRCA1")
    parser.add_argument("--lw-detector", default="NRCA5")
    parser.add_argument("--fov-pixels", type=int, default=101, help="PSF image size, native pixels")
    parser.add_argument("--oversample", type=int, default=4)
    parser.add_argument("--output", type=Path, default=NIRCAM_PSF_NEA_FILE)
    args = parser.parse_args()

    import stpsf

    # Keep existing entries for filters that are not recomputed.
    existing = {}
    if args.output.exists():
        existing = (yaml.safe_load(args.output.read_text()) or {}).get("filters") or {}

    results = dict(existing)
    for filt in args.filters:
        detector = args.sw_detector if is_short_wavelength(filt) else args.lw_detector
        print(f"{filt} on {detector} ...", flush=True)
        results[filt] = nea_for_filter(stpsf, filt, detector=detector,
                                       fov_pixels=args.fov_pixels, oversample=args.oversample)
        r = results[filt]
        print(f"  NEA = {r['nea_pix']:.2f} native px (range {r['nea_min_pix']:.2f}-{r['nea_max_pix']:.2f}), "
              f"enclosed fraction {r['enclosed_fraction']:.3f}")

    header = (
        "# NIRCam PSF noise-equivalent areas (native pixels) for optimal PSF photometry.\n"
        "# Generated by scripts/compute_psf_nea.py; do not edit by hand.\n"
        f"# STPSF {getattr(stpsf, '__version__', 'unknown')}, {date.today().isoformat()}; "
        f"DET_DIST (distortion, charge diffusion, IPC); fov {args.fov_pixels} px, oversample {args.oversample};\n"
        "# averaged over sub-pixel source offsets (0, 0), (1/2, 0), (0, 1/2), (1/2, 1/2) pixel.\n"
    )
    content = {"filters": {f: results[f] for f in sorted(results)}}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header + yaml.safe_dump(content, sort_keys=False))
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
